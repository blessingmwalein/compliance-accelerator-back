-- Contract 0.15.0 (the reference app's Compliance Framework Mapping screen): a row of that table is one
-- governance area, and the reference screen writes three things on the row itself — a short category label,
-- a control objective in the organisation's own words, and one free-text reference per framework column.
-- Every column here is nullable and nothing is seeded: an area nobody has filled in states nothing, and the
-- screen shows no chip and no dash-for-zero rather than inventing a category.
--
-- The per-framework text is stored in its own table because it is one cell of a matrix the organisation
-- chooses (the frameworks come from `frameworks`, not from a fixed list of six). It is NOT a mapping: the
-- verified requirement links stay in `organisation_mappings`, and a note is the organisation's own
-- unverified statement sitting in the same cell.
--
-- No index is added for the area list: it pages over "governance_areas_organisation_id_archived_at_idx",
-- which a category label does not change. The notes table is read by area id through its unique index.

