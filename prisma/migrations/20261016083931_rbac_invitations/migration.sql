-- ---------------------------------------------------------------------------------------------
-- Lookups that run BEFORE a tenant is known (ADR-0004, row-level security).
--
-- Resolving "is this user a member of this organisation" (the access guard), listing the caller's own
-- organisations, finding an invitation by its emailed token and the platform organisation list cannot be
-- written as ordinary tenant queries: no organisation is chosen yet. Each is a SECURITY DEFINER function
-- with a fixed search_path that takes only values the SERVER already verified (user id from the access
-- token, organisation id from the path, token hash computed here) and returns only what that caller may see.
-- They are the ONLY pre-tenant reads; EXECUTE is granted to the runtime role in prisma/sql/runtime-role.sql.
-- ---------------------------------------------------------------------------------------------

CREATE FUNCTION "fca_membership_of"(p_user uuid, p_organisation uuid)
RETURNS TABLE (
  "membership_id" uuid,
  "role" "membership_role",
  "status" "membership_status",
  "membership_version" integer,
  "organisation_name" text,
  "organisation_timezone" text
)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, pg_temp
AS $$
  SELECT m."id", m."role", m."status", m."version", o."name", o."timezone"
  FROM "memberships" m
  JOIN "organisations" o ON o."id" = m."organisation_id"
  WHERE m."user_id" = p_user AND m."organisation_id" = p_organisation
$$;

CREATE FUNCTION "fca_memberships_of_user"(p_user uuid)
RETURNS TABLE (
  "membership_id" uuid,
  "organisation_id" uuid,
  "organisation_name" text,
  "organisation_timezone" text,
  "role" "membership_role",
  "joined_at" timestamptz
)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, pg_temp
AS $$
  SELECT m."id", o."id", o."name", o."timezone", m."role", m."created_at"
  FROM "memberships" m
  JOIN "organisations" o ON o."id" = m."organisation_id"
  WHERE m."user_id" = p_user AND m."status" = 'ACTIVE'
  ORDER BY o."name", o."id"
$$;

CREATE FUNCTION "fca_invitation_by_token"(p_token_hash text)
