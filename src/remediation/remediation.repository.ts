/** A remediation task with the names of what it is about, as the API shows it. */
export interface TaskRecord {
  id: string;
  assessmentItemId: string | null;
  governanceAreaId: string | null;
  requirementId: string | null;
  businessUnitId: string | null;
  frameworkId: string | null;
  title: string;
  description: string | null;
  priority: TaskPriority;
  status: TaskStatus;
  assigneeMembershipId: string | null;
  assigneeName: string | null;
  /** A DATE column: a UTC-midnight Date whose UTC day is the calendar day. Null = no deadline set. */
  dueDate: Date | null;
  autoGenerated: boolean;
  snapshotCurrentMaturity: number | null;
  snapshotTargetMaturity: number | null;
  snapshotGap: number | null;
  snapshotRiskLevel: RiskLevel | null;
  createdByUserId: string;
  completedAt: Date | null;
  completedByUserId: string | null;
  verifiedAt: Date | null;
  verifiedByUserId: string | null;
  createdAt: Date;
  updatedAt: Date;
  version: number;
  governanceAreaName: string | null;
  requirementRef: string | null;
  requirementTitle: string | null;
  businessUnitName: string | null;
  frameworkCode: string | null;
}

/** What a person writes on a task: the five editable columns. */
export interface TaskWritable {
  title: string;
  description: string | null;
  priority: TaskPriority;
  assigneeMembershipId: string | null;
  dueDate: Date | null;
}

/** What a task is about. Only a create carries these: a task's subject never changes afterwards. */
export interface TaskSubject {
  assessmentItemId?: string | null;
  governanceAreaId?: string | null;
  requirementId?: string | null;
  businessUnitId?: string | null;
  frameworkId?: string | null;
}

/**
 * The ratings the task was raised for, frozen into the row. A task outlives the cycle that produced it, so
 * what it says about the maturity and the risk it answers for must not move when the item is re-scored.
 */
export interface TaskSnapshot {
  snapshotCurrentMaturity: number | null;
  snapshotTargetMaturity: number | null;
  snapshotGap: number | null;
  snapshotRiskLevel: RiskLevel | null;
}

/** Everything needed to insert a task row (`created_by_user_id` is NOT NULL and comes from the request). */
export type TaskCreateData = TaskWritable &
  TaskSubject &
  TaskSnapshot & {
    autoGenerated: boolean;
    createdByUserId: string;
  };

/** The columns an edit may write. There is no subject here on purpose (see `TaskSubject`). */
export type TaskUpdateData = Partial<TaskWritable> & TaskLifecycleFields;

/** The timestamps a status change writes, beside the new status. */
export interface TaskLifecycleFields {
  status?: TaskStatus;
  completedAt?: Date | null;
  completedByUserId?: string | null;
  /** `verified_at` MUST be cleared when a VERIFIED task reopens: the table's CHECK ties it to the status. */
  verifiedAt?: Date | null;
  verifiedByUserId?: string | null;
}

/** The item a task may be raised for: the finding, with the ratings its snapshot freezes. */
export interface TaskItemRatings {
  id: string;
  currentMaturity: number | null;
  targetMaturity: number | null;
  gap: number | null;
  riskLevel: RiskLevel | null;
}

/** The snapshot columns of a task: nothing is frozen for a task that points at no assessment item. */
export const snapshotOf = (item: TaskItemRatings | null): TaskSnapshot => ({
  snapshotCurrentMaturity: item?.currentMaturity ?? null,
  snapshotTargetMaturity: item?.targetMaturity ?? null,
  snapshotGap: item?.gap ?? null,
  snapshotRiskLevel: item?.riskLevel ?? null,
});

/** One assessed subject of an assessment, with the ratings it carries. */
export interface GapItemRecord {
  id: string;
  governanceAreaId: string | null;
  requirementId: string | null;
  businessUnitId: string | null;
  frameworkId: string | null;
  currentMaturity: number | null;
  targetMaturity: number | null;
  gap: number | null;
  riskLevel: RiskLevel | null;
  findings: string | null;
  governanceAreaName: string | null;
  requirementRef: string | null;
  requirementTitle: string | null;
  businessUnitName: string | null;
  frameworkCode: string | null;
}

export interface AssessmentRecord {
  id: string;
  title: string;
  status: string;
}

/** The active statuses, spelled the way Prisma's `in` filter wants them. */
const ACTIVE_STATUSES_QUERY = [...ACTIVE_STATUSES] as TaskStatus[];

const SELECT = {
  id: true,
  assessmentItemId: true,
  governanceAreaId: true,
  requirementId: true,
  businessUnitId: true,
  frameworkId: true,
  title: true,
  description: true,
  priority: true,
  status: true,
  assigneeMembershipId: true,
  dueDate: true,
  autoGenerated: true,
  snapshotCurrentMaturity: true,
  snapshotTargetMaturity: true,
  snapshotGap: true,
  snapshotRiskLevel: true,
  createdByUserId: true,
  completedAt: true,
  completedByUserId: true,
  verifiedAt: true,
  verifiedByUserId: true,
  createdAt: true,
  updatedAt: true,
  version: true,
  assignee: { select: { user: { select: { fullName: true } } } },
  governanceArea: { select: { name: true } },
  requirement: { select: { ref: true, title: true } },
  businessUnit: { select: { name: true } },
  framework: { select: { code: true } },
} as const;

type TaskRow = Omit<
  TaskRecord,
  | 'assigneeName'
  | 'governanceAreaName'
  | 'requirementRef'
  | 'requirementTitle'
  | 'businessUnitName'
  | 'frameworkCode'
> & {
  assignee: { user: { fullName: string } } | null;
  governanceArea: { name: string } | null;
  requirement: { ref: string; title: string } | null;
  businessUnit: { name: string } | null;
  framework: { code: string } | null;
};

const toTaskRecord = ({
  assignee,
  governanceArea,
  requirement,
  businessUnit,
  framework,
  ...row
}: TaskRow): TaskRecord => ({
  ...row,
  assigneeName: assignee?.user.fullName ?? null,
  governanceAreaName: governanceArea?.name ?? null,
  requirementRef: requirement?.ref ?? null,
  requirementTitle: requirement?.title ?? null,
  businessUnitName: businessUnit?.name ?? null,
  frameworkCode: framework?.code ?? null,
});

const ITEM_SELECT = {
  id: true,
  governanceAreaId: true,
  requirementId: true,
  businessUnitId: true,
  frameworkId: true,
  currentMaturity: true,
  targetMaturity: true,
  gap: true,
  riskLevel: true,
  findings: true,
  governanceArea: { select: { name: true } },
  requirement: { select: { ref: true, title: true } },
  businessUnit: { select: { name: true } },
  framework: { select: { code: true } },
} as const;

type ItemRow = Omit<
  GapItemRecord,
  | 'governanceAreaName'
  | 'requirementRef'
  | 'requirementTitle'
  | 'businessUnitName'
  | 'frameworkCode'
> & {
  governanceArea: { name: string } | null;
  requirement: { ref: string; title: string } | null;
  businessUnit: { name: string } | null;
  framework: { code: string } | null;
};

const toGapItem = ({
  governanceArea,
  requirement,
  businessUnit,
  framework,
  ...row
}: ItemRow): GapItemRecord => ({
  ...row,
  governanceAreaName: governanceArea?.name ?? null,
  requirementRef: requirement?.ref ?? null,
  requirementTitle: requirement?.title ?? null,
  businessUnitName: businessUnit?.name ?? null,
  frameworkCode: framework?.code ?? null,
});

/** Case-insensitive `contains`, spelled once. */
const contains = (value: string) => ({ contains: value, mode: 'insensitive' as const });

/**
 * Remediation tasks of the CURRENT organisation, plus the reads a task needs to be valid here: the
 * organisation's time zone and due-days policy, the assessment and the items of it that have a gap, and
 * the subjects and members a task may point at. Conventions follow `MembershipsRepository`: every method
 * takes the unit-of-work transaction and pins `organisationId`.
 *
 * The append-only timeline lives in `RemediationTimelineRepository`; nothing here writes an event row.
 */
@Injectable()
export class RemediationRepository extends TenantRepository {
  constructor(requestContext: RequestContext) {
    super(requestContext);
  }

  /**
   * Oldest first (ids are UUIDv7); fetches one extra row to detect another page.
   *
   * `overdue` compares the DATE column against the organisation's calendar today (a UTC-midnight Date):
   * `true` = strictly before it, `false` = that day or later. A task with no due date matches neither,
   * because SQL finds a comparison with NULL not true — an absent deadline is never a verdict.
   */
  async list(
    tx: Tx,
    options: {
      limit: number;
      today: Date;
      after?: string;
      status?: TaskStatus;
      priority?: TaskPriority;
      assigneeMembershipId?: string;
      businessUnitId?: string;
      frameworkId?: string;
      overdue?: boolean;
      q?: string;
    },
  ): Promise<TaskRecord[]> {
    const rows = await tx.remediationTask.findMany({
      where: {
        organisationId: this.organisationId,
        ...(options.after ? { id: { gt: options.after } } : {}),
        ...(options.status ? { status: options.status } : {}),
        ...(options.priority ? { priority: options.priority } : {}),
        ...(options.assigneeMembershipId
          ? { assigneeMembershipId: options.assigneeMembershipId }
          : {}),
        ...(options.businessUnitId ? { businessUnitId: options.businessUnitId } : {}),
        ...(options.frameworkId ? { frameworkId: options.frameworkId } : {}),
        ...(options.overdue === undefined
          ? {}
          : options.overdue
            ? { dueDate: { lt: options.today } }
            : { dueDate: { gte: options.today } }),
        ...(options.q
          ? {
              OR: [
                { title: contains(options.q) },
                { description: contains(options.q) },
                { governanceArea: { name: contains(options.q) } },
                { businessUnit: { name: contains(options.q) } },
                {
                  requirement: {
                    OR: [{ ref: contains(options.q) }, { title: contains(options.q) }],
                  },
                },
                { framework: { code: contains(options.q) } },
              ],
            }
          : {}),
      },
      orderBy: { id: 'asc' },
      take: options.limit + 1,
      select: SELECT,
    });
    return rows.map(toTaskRecord);
  }

  async findById(tx: Tx, id: string): Promise<TaskRecord | null> {
    const row = await tx.remediationTask.findFirst({
      where: { id, organisationId: this.organisationId },
      select: SELECT,
    });
    return row ? toTaskRecord(row) : null;
  }

  /** The rows with these ids, in id order (reads a set-based insert back with its subject names). */
  async listByIds(tx: Tx, ids: string[]): Promise<TaskRecord[]> {
    if (ids.length === 0) return [];
    const rows = await tx.remediationTask.findMany({
      where: { organisationId: this.organisationId, id: { in: ids } },
      orderBy: { id: 'asc' },
      select: SELECT,
    });
    return rows.map(toTaskRecord);
  }

  async create(tx: Tx, data: TaskCreateData): Promise<TaskRecord> {
    const row = await tx.remediationTask.create({
      data: { ...data, organisationId: this.organisationId },
      select: SELECT,
    });
    return toTaskRecord(row);
  }

  /**
   * Inserts many tasks with ONE statement (a per-row loop against a distant Neon is a round trip each).
   * The ids are made here so the caller can read the rows back; they come out in id order.
   */
  async createMany(tx: Tx, rows: TaskCreateData[]): Promise<string[]> {
    if (rows.length === 0) return [];
    const data = rows.map((row) => ({
      ...row,
      id: uuidv7(),
      organisationId: this.organisationId,
    }));
    await tx.remediationTask.createMany({ data });
    return data.map((row) => row.id);
  }

  /** Optimistic update: false when the row changed since `version` was read. */
  async update(tx: Tx, id: string, version: number, data: TaskUpdateData): Promise<boolean> {
    const result = await tx.remediationTask.updateMany({
      where: { id, version, organisationId: this.organisationId },
      data: { ...data, version: { increment: 1 } },
    });
    return result.count === 1;
  }

  /**
   * Which of these assessment items already have a task in an ACTIVE status, from any assessment and
   * whoever created it: a re-run neither duplicates nor resurrects archived work.
   */
  async itemIdsWithActiveTask(tx: Tx, itemIds: string[]): Promise<Set<string>> {
    if (itemIds.length === 0) return new Set();
    const rows = await tx.remediationTask.findMany({
      where: {
        organisationId: this.organisationId,
        assessmentItemId: { in: itemIds },
        status: { in: ACTIVE_STATUSES_QUERY },
      },
      select: { assessmentItemId: true },
    });
    return new Set(rows.flatMap((row) => (row.assessmentItemId ? [row.assessmentItemId] : [])));
  }

  // ---- what generate reads

  /** The assessment of this organisation with this id, or null (another tenant's is not visible). */
  findAssessment(tx: Tx, id: string): Promise<AssessmentRecord | null> {
    return tx.assessment.findFirst({
      where: { id, organisationId: this.organisationId },
      select: { id: true, title: true, status: true },
    });
  }

  /** The items of this assessment that HAVE a gap (a gap above zero); an unassessed item is not one. */
  async gapItems(tx: Tx, assessmentId: string): Promise<GapItemRecord[]> {
    const rows = await tx.assessmentItem.findMany({
      where: { organisationId: this.organisationId, assessmentId, gap: { gt: 0 } },
      orderBy: { id: 'asc' },
      select: ITEM_SELECT,
    });
    return rows.map(toGapItem);
  }

  // ---- the organisation's own rules

  /** The tenant's IANA zone: a due date and "overdue" are calendar days in it, never in UTC. */
  async timezone(tx: Tx): Promise<string> {
    const row = await tx.organisation.findUnique({
      where: { id: this.organisationId },
      select: { timezone: true },
    });
    if (!row) {
      throw new AppException(ErrorCode.NotFound, HttpStatus.NOT_FOUND, 'Organisation not found.');
    }
    return row.timezone;
  }

  // ---- the checks that make a task valid in THIS organisation

  /** An ACTIVE member of this organisation, with the name a reassignment line reads. */
  async findActiveMember(
    tx: Tx,
    membershipId: string,
  ): Promise<{ id: string; fullName: string } | null> {
    const row = await tx.membership.findFirst({
      where: { id: membershipId, organisationId: this.organisationId, status: 'ACTIVE' },
      select: { id: true, user: { select: { fullName: true } } },
    });
    return row ? { id: row.id, fullName: row.user.fullName } : null;
  }

  /** A governance area of this organisation, in any state (an archived one still holds work). */
  findArea(tx: Tx, id: string): Promise<{ id: string } | null> {
    return tx.governanceArea.findFirst({
      where: { id, organisationId: this.organisationId },
      select: { id: true },
    });
  }

  /** A business unit of this organisation, in any state. */
  findBusinessUnit(tx: Tx, id: string): Promise<{ id: string } | null> {
    return tx.businessUnit.findFirst({
      where: { id, organisationId: this.organisationId },
      select: { id: true },
    });
  }

  /**
   * An assessment item of this organisation: the finding a task may fix. The ratings come with it because a
   * task freezes the ones it was raised for (`TaskSnapshot`), so this must not be a second read.
   */
  findItem(tx: Tx, id: string): Promise<TaskItemRatings | null> {
    return tx.assessmentItem.findFirst({
      where: { id, organisationId: this.organisationId },
      select: { id: true, currentMaturity: true, targetMaturity: true, gap: true, riskLevel: true },
    });
  }

  /** A requirement of a loaded framework version (global content, so it carries no organisation). */
  findRequirement(tx: Tx, id: string): Promise<{ id: string } | null> {
    return tx.requirement.findFirst({ where: { id }, select: { id: true } });
  }

  findFramework(tx: Tx, id: string): Promise<{ id: string } | null> {
    return tx.framework.findFirst({ where: { id }, select: { id: true } });
  }
}
